document.addEventListener('DOMContentLoaded', () => {
    const gate = document.getElementById('licenseGate');
    const form = document.getElementById('licenseGateForm');
    const input = document.getElementById('licenseKeyInput');
    const submit = document.getElementById('licenseGateSubmit');
    const feedback = document.getElementById('licenseGateFeedback');
    const title = document.getElementById('licenseGateTitle');
    const description = document.getElementById('licenseGateDescription');
    const signupText = document.getElementById('licenseGateSignupText');
    const signupLink = document.getElementById('licenseGateSignupLink');
    const resetButton = document.getElementById('licenseGateReset');
    const resetModal = document.getElementById('licenseGateResetModal');
    const resetCancel = document.getElementById('licenseGateResetCancel');
    const resetConfirm = document.getElementById('licenseGateResetConfirm');
    const expiredAccessNotice = document.getElementById('expiredAccessNotice');
    const expiredAccessNoticeText = document.getElementById('expiredAccessNoticeText');
    const expiredAccessPlansBtn = document.getElementById('expiredAccessPlansBtn');
    const entitlementMonitor = window.MerlinEntitlementMonitor.createEntitlementMonitor({
        getStatus: () => window.electronAPI.auth.status(),
        onAuthenticated: applyEntitlementStatus
    });
    let language = 'ptbr';
    let busy = true;
    let mode = 'checking';
    let rateLimitUntil = 0;
    let rateLimitTimer = null;

    function setApplicationLocked(locked) {
        for (const element of document.body.children) {
            if (element !== gate && element !== resetModal && element.tagName !== 'SCRIPT') element.inert = locked;
        }
    }

    function messages() {
        return licenseGateTranslations[language] || licenseGateTranslations.ptbr;
    }

    function renderLanguage() {
        const text = messages();
        document.getElementById('licenseGateEyebrow').textContent = text.eyebrow;
        title.textContent = mode === 'checking' ? text.checkingTitle : text.title;
        description.textContent = mode === 'checking' ? text.checkingDescription : text.description;
        document.getElementById('licenseGateLabel').textContent = text.label;
        document.getElementById('licenseGateSubmitText').textContent = text.submit;
        document.getElementById('licenseGatePrivacy').textContent = text.privacy;
        signupText.textContent = text.signupText;
        signupLink.textContent = text.signupLink;
        expiredAccessNoticeText.textContent = text.expired;
        expiredAccessPlansBtn.textContent = text.expiredAction;
        if (isRateLimited()) renderRateLimitCountdown();
    }

    function isRateLimited() {
        return Date.now() < rateLimitUntil;
    }

    function updateSubmitState() {
        submit.disabled = busy || isRateLimited() || !isCompleteKey(input.value);
        resetButton.disabled = busy || !isCompleteKey(input.value);
    }

    function formatResetAvailability(retryAt) {
        const date = new Date(retryAt || '');
        if (Number.isNaN(date.getTime())) return '';
        return new Intl.DateTimeFormat('pt-BR', {
            dateStyle: 'long',
            timeStyle: 'short',
            timeZone: 'America/Sao_Paulo'
        }).format(date);
    }

    function renderRateLimitCountdown() {
        const text = messages();
        const remainingSeconds = Math.max(0, Math.ceil((rateLimitUntil - Date.now()) / 1000));

        if (remainingSeconds <= 0) {
            rateLimitUntil = 0;
            if (rateLimitTimer) {
                clearInterval(rateLimitTimer);
                rateLimitTimer = null;
            }
            if (feedback.dataset.code === 'rate_limited') {
                feedback.textContent = text.rate_limited_ready;
                feedback.dataset.type = 'info';
                feedback.dataset.code = '';
            }
            updateSubmitState();
            return;
        }

        feedback.textContent = `${text.rate_limited} ${text.rate_limited_countdown.replace('{seconds}', remainingSeconds)}`;
        feedback.dataset.type = 'error';
        feedback.dataset.code = 'rate_limited';
        updateSubmitState();
    }

    function startRateLimitCooldown(durationMs = 60_000) {
        rateLimitUntil = Math.max(rateLimitUntil, Date.now() + durationMs);
        if (rateLimitTimer) clearInterval(rateLimitTimer);
        renderRateLimitCountdown();
        rateLimitTimer = setInterval(renderRateLimitCountdown, 1000);
    }

    async function loadLanguage() {
        try {
            const config = await window.electronAPI.getConfig();
            language = config.language || 'ptbr';
        } catch (_) {
            language = 'ptbr';
        }
        renderLanguage();
    }

    function setMode(nextMode) {
        mode = nextMode;
        gate.classList.toggle('is-checking', nextMode === 'checking');
        gate.setAttribute('aria-busy', nextMode === 'checking' ? 'true' : 'false');
        renderLanguage();
    }

    function formatLicenseKey(value) {
        let sanitized = String(value || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
        const hasPrefix = sanitized.startsWith('MERLIN');
        if (hasPrefix) sanitized = sanitized.slice(6);
        sanitized = sanitized.slice(0, 12);
        if (!sanitized) return hasPrefix ? 'MERLIN-' : '';

        const groups = sanitized.match(/.{1,4}/g) || [];
        return hasPrefix
            ? `MERLIN-${groups.join('-')}`
            : groups.join('-');
    }

    function normalizeLicenseKey(value) {
        const formatted = formatLicenseKey(value);
        if (!formatted) return '';
        return formatted.startsWith('MERLIN-') ? formatted : `MERLIN-${formatted}`;
    }

    function isCompleteKey(value) {
        return /^MERLIN-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}$/.test(normalizeLicenseKey(value));
    }

    function setBusy(value, message) {
        busy = value;
        gate.classList.toggle('is-busy', value);
        input.disabled = value;
        updateSubmitState();
        feedback.dataset.type = value ? 'info' : feedback.dataset.type;
        if (message) feedback.textContent = message;
    }

    function showError(code) {
        entitlementMonitor.stop();
        setApplicationLocked(true);
        expiredAccessNotice.hidden = true;
        gate.hidden = false;
        gate.classList.remove('is-authenticated');
        setMode('prompt');
        const text = messages();
        feedback.dataset.type = 'error';
        feedback.dataset.code = code || '';
        if (code === 'rate_limited') {
            startRateLimitCooldown();
        } else {
            feedback.textContent = text[code] || text.server_error;
        }
        setBusy(false);
        input.focus();
    }

    function unlock(sessionData = null) {
        gate.classList.add('is-authenticated');
        setApplicationLocked(false);
        applyEntitlementStatus(sessionData);
        entitlementMonitor.start();
        window.dispatchEvent(new CustomEvent('merlin-authenticated', { detail: { expired: isExpiredSession(sessionData) } }));
        setTimeout(() => {
            gate.hidden = true;
        }, 260);
    }

    function isExpiredSession(sessionData) {
        return sessionData?.license?.status === 'expired' || sessionData?.expired === true;
    }

    function applyEntitlementStatus(sessionData = null) {
        const expired = isExpiredSession(sessionData);
        expiredAccessNotice.hidden = !expired;
    }

    input.addEventListener('input', () => {
        const cursorAtEnd = input.selectionStart === input.value.length;
        input.value = formatLicenseKey(input.value);
        if (cursorAtEnd) input.setSelectionRange(input.value.length, input.value.length);
        updateSubmitState();
        if (isRateLimited()) {
            renderRateLimitCountdown();
            return;
        }
        feedback.textContent = messages().missing;
        feedback.dataset.type = 'info';
        feedback.dataset.code = '';
    });

    signupLink.addEventListener('click', async () => {
        if (signupLink.disabled) return;
        const previousFeedback = feedback.textContent;
        const previousType = feedback.dataset.type;
        const previousCode = feedback.dataset.code;
        signupLink.disabled = true;
        feedback.textContent = messages().signupOpening;
        feedback.dataset.type = 'info';
        feedback.dataset.code = '';
        try {
            const result = await window.electronAPI.auth.openSignup();
            if (!result?.ok) throw new Error('open_signup_failed');
            feedback.textContent = previousFeedback;
            feedback.dataset.type = previousType || 'info';
            feedback.dataset.code = previousCode || '';
        } catch (_) {
            feedback.textContent = messages().signupFailed;
            feedback.dataset.type = 'error';
        } finally {
            signupLink.disabled = false;
        }
    });

    expiredAccessPlansBtn.addEventListener('click', async () => {
        if (expiredAccessPlansBtn.disabled) return;
        const originalLabel = expiredAccessPlansBtn.textContent;
        expiredAccessPlansBtn.disabled = true;
        try {
      // The handoff identifies the exact license in the public account page.
      // Expired licenses are allowed to create this read-only handoff, while
      // revoked licenses remain blocked by the API.
      await window.electronAPI.auth.openAccess();
        } finally {
            expiredAccessPlansBtn.disabled = false;
            expiredAccessPlansBtn.textContent = originalLabel;
        }
    });

    function closeResetModal() {
        resetModal.hidden = true;
    }

    resetButton.addEventListener('click', () => {
        if (!busy && isCompleteKey(input.value)) resetModal.hidden = false;
    });
    resetCancel.addEventListener('click', closeResetModal);
    resetModal.addEventListener('click', event => {
        if (event.target === resetModal) closeResetModal();
    });
    resetConfirm.addEventListener('click', async () => {
        closeResetModal();
        setBusy(true, 'Redefinindo dispositivo...');
        const result = await window.electronAPI.auth.resetHwid(normalizeLicenseKey(input.value));
        if (result?.ok) {
            feedback.dataset.type = 'success';
            feedback.textContent = 'Dispositivo desvinculado. Valide sua chave para ativar este computador.';
            setBusy(false);
            input.focus();
            return;
        }
        feedback.dataset.type = 'error';
        if (result?.code === 'hwid_reset_unavailable') {
            const availability = formatResetAvailability(result.retryAt);
            feedback.textContent = availability
                ? `O reset mensal desta licença ficará disponível em ${availability}.`
                : 'O reset mensal desta licença ainda não está disponível.';
        } else {
            feedback.textContent = 'Não foi possível resetar este dispositivo. Confira a chave e tente novamente.';
        }
        setBusy(false);
    });

    form.addEventListener('submit', async event => {
        event.preventDefault();
        if (busy || isRateLimited() || !isCompleteKey(input.value)) return;

        setMode('prompt');
        setBusy(true, messages().validating);
        try {
            const result = await window.electronAPI.auth.login(normalizeLicenseKey(input.value));
            if (result.authenticated) {
                input.value = '';
                unlock(result);
                return;
            }
            showError(result.code);
        } catch (_) {
            showError('unavailable');
        }
    });

    window.electronAPI.auth.onRequired(data => showError(data?.code || 'invalid_key'));
    window.addEventListener('merlin-language-changed', loadLanguage);
    window.addEventListener('merlin-logout', () => {
        entitlementMonitor.stop();
        input.value = '';
        expiredAccessNotice.hidden = true;
        showError('missing');
    });
    document.addEventListener('visibilitychange', () => {
        if (document.visibilityState === 'visible') entitlementMonitor.check();
    });

    setApplicationLocked(true);
    (async () => {
        await loadLanguage();

        const hasSession = await window.electronAPI.auth.hasSession();
        if (!hasSession) {
            setMode('prompt');
            feedback.textContent = messages().missing;
            feedback.dataset.type = 'info';
            setBusy(false);
            input.focus();
            return;
        }

        setMode('checking');
        feedback.textContent = messages().checking;
        feedback.dataset.type = 'info';

        try {
            const result = await window.electronAPI.auth.status();
            if (result.authenticated) {
                unlock(result);
                return;
            }
            showError(result.code);
        } catch (_) {
            showError('unavailable');
        }
    })();
});
